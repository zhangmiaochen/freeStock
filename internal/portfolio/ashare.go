package portfolio

// A 股代码前缀白名单 —— **单一事实来源**。
//
// 对应原实现的 `_load_market_frame`（portfolio_service.py:1256-1258）：
//
//	raw = raw[raw["ts_code"].str.match(
//	    r"^(?:600|601|603|605|688|689|000|001|002|003|300|301)\d{3}\.(?:SH|SZ)$", na=False)]
//
// 这是**全市场帧的股票集定义**，低吸广度就绪数就是在这个帧上数的
// （`portfolio_service.py:1841-1853`）。所以凡是要对齐"原版全市场"的地方，
// 都必须套这道白名单。
//
// ⚠ 它排除的东西比"北交所"多。实测本项目库里的分布：
//
//	600/601/603/605 → sh-main    ✓ 在名单内
//	000/001/002/003 → sz-main    ✓
//	300/301         → chinext    ✓
//	688/689         → star       ✓
//	920             → bse        ✗ 北交所，62,379 行
//	302             → chinext    ✗ **新版创业板代码段**，243 行 —— 也在名单外
//
// 所以不能图省事写成 `market <> 'bse'`：那样会漏掉 302。必须按前缀判断。
//
// ASharePrefixSQL 是同一份名单的 SQL 形式，供 `substr(ts_code,1,3) IN (...)` 使用；
// 两处必须同步修改。
const ASharePrefixSQL = `'600','601','603','605','688','689','000','001','002','003','300','301'`

// IsAShareBareCode 判断**裸 6 位**代码（`stock_strength.ts_code` 的格式）是否在白名单内。
//
// 原版的正则带交易所后缀（`\.(?:SH|SZ)$`），裸码没有后缀，所以只需判前 3 位 + 长度。
// 注意：本函数对**指数**代码（如 `000300`）也会返回 true —— 与原版正则一致
// （原版正则在 `000300.SH` 上也匹配）。调用方若需要排除指数，需另行判断。
func IsAShareBareCode(code string) bool {
	if len(code) != 6 {
		return false
	}
	switch code[:3] {
	case "600", "601", "603", "605", "688", "689",
		"000", "001", "002", "003", "300", "301":
		return true
	}
	return false
}
